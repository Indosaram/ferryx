function block(source, signature) {
  const start = source.indexOf(signature);
  if (start < 0 || source.indexOf(signature, start + 1) >= 0) throw new Error(`Nonunique/missing ${signature}`);
  const open = source.indexOf('{', start);
  let depth = 1;
  let end = open + 1;
  // These inspected blocks contain no braces in comments or strings.
  while (depth && end < source.length) {
    if (source[end] === '{') depth++;
    if (source[end] === '}') depth--;
    end++;
  }
  if (depth) throw new Error(`Unclosed ${signature}`);
  return source.slice(start, end);
}
