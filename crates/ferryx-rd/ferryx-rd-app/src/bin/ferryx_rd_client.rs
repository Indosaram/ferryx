fn run_client(mut cli: Cli) -> Result<()> {
    let udp_port = cli.udp_port.unwrap_or_else(|| {
        if cli.tcp_port == DEFAULT_TCP_PORT {
            DEFAULT_UDP_PORT
        } else {
            cli.tcp_port.saturating_add(1)
        }
    });

    let target_frames = cli.frames.unwrap_or(u64::MAX);

    let start_time = Instant::now();

    let session_config = SessionConfig {
        host: cli.host.clone(),
        tcp_port: cli.tcp_port,
        udp_port,
        client_name: cli.client_name.clone(),
        capabilities: SessionConfig::implemented_capabilities(),
        pairing_store_path: cli.pairing_store.clone(),
        connect_timeout: Duration::from_secs(10),
        handshake_ack_timeout: Duration::from_secs(10),
    };

    info!(
        host = %cli.host,
        tcp_port = cli.tcp_port,
        udp_port = udp_port,
        timeout_secs = ?cli.timeout_secs,
        "Initializing headless client session"
    );

    let session =
        ClientSession::new(session_config).context("failed to construct ClientSession")?;

    // Parsec-style reconnect: with no --pin/--psk-hex/--pairing-id, match the
    // stored pairing record by computer (host) name or latest matching pairing.
    if cli.pin.is_none() && cli.psk_hex.is_none() && cli.pairing_id.is_none() {
        let store = match cli.pairing_store.clone() {
            Some(path) => PairingStore::new(path),
            None => PairingStore::open_default()?,
        };
        let matched = match store.find_by_host(&cli.host) {
            Ok(Some(record)) => Some(record),
            _ => {
                if let Ok(records) = store.load_all() {
                    // Match the saved record by host name or by a previously used
                    // endpoint. `starts_with` on the record name is deliberately
                    // gone: "10.0.0.5" must not match a record named "10".
                    records.into_iter().rev().find(|r| {
                        cli.host.eq_ignore_ascii_case(&r.name)
                            || r.last_endpoint.as_ref().is_some_and(|endpoint| {
                                endpoint.host.eq_ignore_ascii_case(&cli.host)
                            })
                            || r.endpoint_aliases
                                .iter()
                                .any(|endpoint| endpoint.host.eq_ignore_ascii_case(&cli.host))
                    })
                } else {
                    None
                }
            }
        };
        match matched {
            Some(record) => {
                info!(
                    pairing_id = %record.id,
                    host_name = %record.name,
                    "reconnecting with stored pairing (PIN-less Parsec style)"
                );
                cli.pairing_id = Some(record.id);
            }
            None => {
                eprintln!(
                    "no stored pairing for host '{}' — pair once with --pin, or pass --pairing-id",
                    cli.host
                );
            }
        }
    }

    let ready = match (&cli.pin, &cli.psk_hex) {
        (Some(pin), None) => {
            info!("Initiating bootstrap pairing with host via PIN");
            session
                .pair_with_pin(pin)
                .context("bootstrap pairing failed")?
        }
        (None, Some(psk_hex)) => {
            let key = parse_hex_32(psk_hex).context("invalid --psk-hex argument")?;
            let pairing_id = cli
                .pairing_id
                .clone()
                .unwrap_or_else(|| "00000000-0000-0000-0000-000000000000".to_string());
            let pairing = PairingRecord {
                id: pairing_id,
                name: cli.host.clone(),
                key,
                added_at_unix_ms: 0,
                last_endpoint: None,
                endpoint_aliases: Vec::new(),
                relay_url: cli.relay_url.clone(),
                relay_host_id: cli.relay_host_id.clone(),
                trust: ferryx_rd_proto::PairingTrust::Owner,
            };
            info!(pairing_id = %pairing.id, "Connecting with explicit PSK");
            session
                .connect_with_pairing(pairing)
                .context("handshake with explicit PSK failed")?
        }
        (None, None) => {
            if let Some(pairing_id) = &cli.pairing_id {
                info!(pairing_id = %pairing_id, "Reconnecting with stored pairing record");
                session
                    .reconnect(pairing_id)
                    .context("reconnect with stored pairing failed")?
            } else {
                bail!("either --pin, --psk-hex, or --pairing-id must be provided");
            }
        }
        (Some(_), Some(_)) => {
            unreachable!("clap enforces conflicts between pin and psk_hex");
        }
    };

    info!(
        host_name = %ready.server.name,
        width = ready.server.width,
        height = ready.server.height,
        version = ready.server.version,
        "Handshake completed, session ready"
    );

    // Spawn TCP control loop
    let mut tcp_runtime = session
        .spawn_tcp_runtime()
        .context("failed to spawn TCP runtime")?;
    if cli.sas {
        session
            .request_secure_attention()
            .context("secure attention unavailable")?;
    }

    session
        .set_udp_read_timeout(Some(Duration::from_millis(5)))
        .context("failed to set UDP read timeout")?;

    let _ = session.send_control(ControlMessage::RequestKeyFrame);

    let running = Arc::new(AtomicBool::new(true));
    let r_ctrl = running.clone();
    let _ = ctrlc_handler(move || {
        r_ctrl.store(false, Ordering::SeqCst);
    });

    let first_frame_seen = Arc::new(AtomicBool::new(false));

    let mut latency_recorder = LatencyRecorder::new();
    let mut decoder: Option<HevcDecoder> = None;
    let mut current_codec: Option<ferryx_rd_decode::CodecKind> = None;
    let mut last_logged_size: Option<(u32, u32)> = None;
    let mut decoded_frames: u64 = 0;

    let has_options_requested =
        cli.fps.is_some() || cli.codec.is_some() || cli.scale.is_some() || cli.display.is_some();
    let mut stream_options_sent = false;
    let mut stream_options_active = false;

    let frame_rx = Arc::new(FrameQueue::with_config(
        FrameQueueConfig::for_fps(u32::from(cli.fps.unwrap_or(60)), PlayoutMode::Immediate),
        session.receiver_trace(),
    ));
    let frame_tx = frame_rx.clone();
    let session_udp = session.clone();
    let r_udp = running.clone();

    // Optional cursor-nudge driver: keeps compositors that only produce frames
    // on change (static wlroots sessions) feeding the pipeline, and exercises
    // the host input-injection path end-to-end.
    if let Some(nudge_ms) = cli.nudge_ms.filter(|value| *value > 0) {
        let session_nudge = session.clone();
        let r_nudge = running.clone();
        let _first = Arc::clone(&first_frame_seen);
        std::thread::Builder::new()
            .name("ferryx-rd-client-nudge".into())
            .spawn(move || {
                let mut flip = false;
                // The nudge only makes sense once streaming has actually started:
                // injecting mouse moves before the first video frame would churn
                // the host during handshake for no benefit.
                while r_nudge.load(Ordering::Relaxed) && !_first.load(Ordering::Relaxed) {
                    std::thread::sleep(Duration::from_millis(nudge_ms.clamp(1, 20)));
                }
                while r_nudge.load(Ordering::Relaxed) {
                    let x = if flip { 0.501_5 } else { 0.5 };
                    flip = !flip;
                    let event = InputEvent {
                        event_type: InputEventType::MouseMove,
                        x,
                        y: 0.5,
                        key_code: 0,
                        modifiers: Modifiers::empty(),
                        scroll_dx: 0.0,
                        scroll_dy: 0.0,
                    };
                    if let Err(error) = session_nudge.send_input(event) {
                        debug!(%error, "nudge input rejected");
                    }
                    std::thread::sleep(Duration::from_millis(nudge_ms));
                }
            })
            .ok();
    }

    let latest_frame: LatestFrameHolder = Arc::new(std::sync::Mutex::new(None));
    let frame_metadata: FrameMetadataHolder = Arc::new(std::sync::Mutex::new(None));
    let frame_snapshot: FrameSnapshotHolder = Arc::new(std::sync::Mutex::new(None));

    let mut agent_server_handle: Option<std::thread::JoinHandle<std::io::Result<()>>> = None;
    let mut agent_spawn_result = Ok(());
    let mut agent_server_stop: Option<tokio::sync::watch::Sender<bool>> = None;
    let mut mcp_handle = None;
    let mut mcp_stop = None;
    if cli.agent_server.is_some() || cli.mcp {
        let scale = ready.server.scale.max(0.1);
        let logical_w = ready.server.width as u32;
        let logical_h = ready.server.height as u32;
        let phys_w = (logical_w as f32 * scale).round() as u32;
        let phys_h = (logical_h as f32 * scale).round() as u32;
        let backend = Arc::new(ClientBackend {
            session: session.clone(),
            pairing_id: cli.pairing_id.clone(),
            screen_info: ScreenInfo {
                width: phys_w,
                height: phys_h,
                scale: ready.server.scale,
                logical_width: Some(logical_w),
                logical_height: Some(logical_h),
                monitors: vec![ferryx_rd_app::agent_input::MonitorInfo {
                    id: 0,
                    name: "Primary Display".to_string(),
                    x: 0,
                    y: 0,
                    width: phys_w,
                    height: phys_h,
                    scale: ready.server.scale,
                    is_primary: true,
                }],
                connected_host: cli.host.clone(),
            },
            latest_frame: latest_frame.clone(),
            frame_metadata: frame_metadata.clone(),
            frame_snapshot: frame_snapshot.clone(),
            running: running.clone(),
        });

        if let Some(port_opt) = cli.agent_server {
            let port = port_opt.unwrap_or(19735);
            let b = backend.clone();
            let r_agent = running.clone();
            let (stop_tx, stop_rx) = tokio::sync::watch::channel(false);
            agent_server_stop = Some(stop_tx);
            let token = if let Some(ref t) = cli.agent_token {
                Some(t.clone())
            } else if let Ok(env_token) = std::env::var("MAHO_AGENT_TOKEN") {
                Some(env_token)
            } else if cli.allow_unauthenticated_agent {
                None
            } else {
                let random_bytes = rand::random::<[u8; 16]>();
                let gen = random_bytes
                    .iter()
                    .map(|b| format!("{:02x}", b))
                    .collect::<String>();
                eprintln!("[ferryx-rd-client] Agent HTTP server auth token: {}", gen);
                Some(gen)
            };
            if token.is_some() {
                eprintln!("[ferryx-rd-client] Agent HTTP server auth token enabled");
            }
            agent_spawn_result = std::thread::Builder::new()
                .name("ferryx-rd-client-agent-server".into())
                .spawn(move || {
                    let result = run_agent_server_runtime(async move {
                        let addr = std::net::SocketAddr::from(([127, 0, 0, 1], port));
                        let (shutdown_tx, shutdown_rx) = tokio::sync::watch::channel(false);
                        let (mut server, addr) = AgentServer::bind(addr, b).await?;
                        if let Some(ref t) = token {
                            server.set_auth_token(t);
                        }
                        info!("Headless agent server listening on http://{addr}");
                        let server_task = tokio::spawn(server.run(shutdown_rx));
                        // Owned worker join: returns when a disconnect request
                        // closed the listener, otherwise stops the worker once
                        // the CLI lifecycle signals shutdown - no polling.
                        join_agent_server_worker(server_task, shutdown_tx, stop_rx).await
                    });
                    r_agent.store(false, Ordering::SeqCst);
                    result
                })
                .map(|handle| agent_server_handle = Some(handle))
                .context("failed to spawn agent server thread");
        }

        if cli.mcp {
            let b = backend.clone();
            let (stop_tx, stop_rx) = tokio::sync::watch::channel(false);
            mcp_stop = Some(stop_tx);
            let r_mcp = running.clone();
            let result = std::thread::Builder::new()
                .name("ferryx-rd-client-mcp".into())
                .spawn(move || {
                    let result = tokio::runtime::Builder::new_current_thread()
                        .enable_all()
                        .build()
                        .and_then(|rt| rt.block_on(run_mcp_stdio_until(b, stop_rx)));
                    r_mcp.store(false, Ordering::SeqCst);
                    result
                })
                .context("failed to spawn MCP worker");
            match result {
                Ok(handle) => mcp_handle = Some(handle),
                Err(error) => agent_spawn_result = Err(error),
            }
        }
    }

    let udp_receiver_handle = std::thread::Builder::new()
        .name("ferryx-rd-client-udp-receiver".into())
        .spawn(move || {
            let mut receive_result = Ok(());
            while r_udp.load(Ordering::Relaxed) {
                match session_udp.receive_udp_event() {
                    Ok(SessionEvent::Frame(assembled_frame)) => {
                        let receive_ts = Instant::now();
                        match frame_tx.push((assembled_frame, receive_ts)) {
                            Ok(true) => {
                                if let Err(error) =
                                    session_udp.send_control(ControlMessage::RequestKeyFrame)
                                {
                                    warn!(%error, "queue recovery keyframe request failed");
                                }
                            }
                            Ok(false) => {}
                            Err(error) => {
                                debug!(%error, "media queue closed");
                                break;
                            }
                        }
                    }
                    Ok(SessionEvent::Ping) => {
                        debug!("UDP ping received");
                    }
                    Ok(_) => {}
                    Err(err) => {
                        if let ferryx_rd_app::SessionError::Io(ref io_err) = err {
                            if matches!(
                                io_err.kind(),
                                std::io::ErrorKind::TimedOut | std::io::ErrorKind::WouldBlock
                            ) {
                                std::thread::yield_now();
                                continue;
                            }
                        }
                        warn!(%err, "UDP receiver stopped");
                        receive_result =
                            Err(anyhow::Error::new(err).context("UDP receiver failed"));
                        break;
                    }
                }
            }
            if let Err(error) = frame_tx.stop() {
                error!(%error, "failed to close media queue");
                receive_result = match receive_result {
                    Ok(()) => Err(error),
                    Err(previous) => Err(previous.context(error)),
                };
            }
            receive_result
        })
        .context("failed to spawn UDP receiver thread");

    #[cfg(target_os = "macos")]
    let clipboard_monitor = if cli.watch_clipboard {
        start_clipboard_watch(&session)
    } else {
        None
    };
    #[cfg(not(target_os = "macos"))]
    if cli.watch_clipboard {
        println!("clipboard watch unsupported: local pasteboard monitoring is macOS-only");
    }
    let mut pending_clipboard_send = cli.clipboard_send.clone();
    let ready_at = Instant::now();
    // Set when the media queue closes; the loop then runs one more TCP event
    // drain so control events that arrived before the close are not dropped.
    let mut media_closed = false;

    info!("Awaiting UDP media datagrams and decoding frames...");

    while agent_spawn_result.is_ok()
        && udp_receiver_handle.is_ok()
        && running.load(Ordering::Relaxed)
    {
        if cli.deadline_expired(start_time.elapsed()) {
            error!(decoded_frames, target_frames, "Session deadline expired");
            break;
        }

        if decoded_frames >= target_frames {
            info!(decoded_frames, "Reached requested target frame count");
            break;
        }

        // Check if TCP runtime emitted an event or error
        while let Ok(event_res) = tcp_runtime.events().try_recv() {
            match event_res {
                Ok(SessionEvent::Ping) => {
                    debug!("TCP heartbeat ping acknowledged");
                }
                Ok(SessionEvent::Clipboard(text)) => {
                    info!("clipboard received: {} bytes", text.len());
                    #[cfg(target_os = "macos")]
                    if let Some(monitor) = clipboard_monitor.as_ref() {
                        if let Err(error) = monitor.apply_remote(&text) {
                            warn!(%error, "failed to apply host clipboard locally");
                        }
                    }
                }
                Ok(SessionEvent::StreamConfig(ref msg)) => match msg {
                    ControlMessage::HostStatus(status) => println!(
                        "host status: {} active guests {:?}",
                        status.active_guest_count(),
                        status.guest_names
                    ),
                    ControlMessage::GuestPermissions(p) => {
                        println!("effective permissions: keyboard={} mouse={} gamepad={} clipboard={} audio={}", p.keyboard, p.mouse, p.gamepad, p.clipboard, p.audio);
                        resolve_clipboard_send(
                            &session,
                            &mut pending_clipboard_send,
                            ready_at.elapsed(),
                            false,
                        )?;
                    }
                    ControlMessage::SessionEnded(ended) => {
                        println!("session ended: {:?}", ended.reason);
                        resolve_clipboard_send(
                            &session,
                            &mut pending_clipboard_send,
                            ready_at.elapsed(),
                            true,
                        )?;
                        running.store(false, Ordering::SeqCst);
                    }
                    ControlMessage::SecureAttentionResponse(response) => {
                        println!("secure attention: {:?}", response.result)
                    }
                    ControlMessage::HostDisplayList(list) => {
                        for d in &list.displays {
                            let primary_str = if d.primary { " (primary)" } else { "" };
                            println!(
                                "host display [{}] {} {}x{}{}",
                                d.index, d.name, d.width, d.height, primary_str
                            );
                        }
                    }
                    ControlMessage::HostPolicy(policy) => {
                        println!(
                            "host policy: input={} clipboard={}",
                            policy.allow_input, policy.allow_clipboard
                        );
                        resolve_clipboard_send(
                            &session,
                            &mut pending_clipboard_send,
                            ready_at.elapsed(),
                            false,
                        )?;
                    }
                    ControlMessage::StreamOptionsActive(active) => {
                        frame_rx.reconfigure(FrameQueueConfig::for_fps(
                            u32::from(active.fps),
                            frame_rx.config()?.playout,
                        ))?;
                        let codec_str = match active.codec {
                            StreamCodecPreference::Auto => "auto",
                            StreamCodecPreference::H264 => "h264",
                            StreamCodecPreference::Hevc => "hevc",
                        };
                        println!(
                            "active config: {}x{} fps={} codec={} display={}",
                            active.width,
                            active.height,
                            active.fps,
                            codec_str,
                            active.display_index
                        );
                        stream_options_active = true;
                        // Decoder recreation on codec or size change:
                        // drop existing decoder so the next keyframe initializes a fresh decoder
                        decoder = None;
                        current_codec = None;
                    }
                    ControlMessage::StreamConfigResponse(response) => {
                        frame_rx.reconfigure(FrameQueueConfig::for_fps(
                            u32::from(response.active.frames_per_second),
                            frame_rx.config()?.playout,
                        ))?;
                    }
                    ControlMessage::StreamConfigReject(reject) => {
                        eprintln!("stream options rejected: {}", reject.message);
                        std::process::exit(1);
                    }
                    _ => {}
                },
                Ok(_) => {}
                Err(err) => {
                    // Non-fatal or timeout errors in polling shouldn't abort immediately unless fatal
                    warn!(%err, "TCP runtime poll error");
                }
            }
        }

        resolve_clipboard_send(
            &session,
            &mut pending_clipboard_send,
            ready_at.elapsed(),
            false,
        )?;
        if media_closed {
            break;
        }

        match frame_rx.recv_timeout(Duration::from_millis(5)) {
            Ok((assembled_frame, receive_ts)) => {
                let is_key = assembled_frame.header.is_key_frame;
                let data = &assembled_frame.data;
                let mut decode_failed = false;
                if decoder.is_none() {
                    match HevcDecoder::from_keyframe_auto(data) {
                        Ok((codec_kind, dec)) => {
                            info!(?codec_kind, "decoder initialized from keyframe");
                            session.set_decoder_backend(format!("{:?}", dec.acceleration()))?;
                            current_codec = Some(codec_kind);
                            decoder = Some(dec);
                        }
                        Err(err) => {
                            decode_failed = true;
                            info!(%err, is_key, size = data.len(), "frame not usable for keyframe decoder init");
                        }
                    }
                } else if is_key {
                    // Check if codec changed in an arriving keyframe
                    if let Ok(new_kind) = ferryx_rd_decode::detect_codec(data) {
                        if current_codec.is_some_and(|c| c != new_kind) {
                            info!(
                                ?current_codec,
                                ?new_kind,
                                "recreating decoder on codec change"
                            );
                            match HevcDecoder::from_keyframe_auto(data) {
                                Ok((k, dec)) => {
                                    current_codec = Some(k);
                                    decoder = Some(dec);
                                }
                                Err(err) => {
                                    decode_failed = true;
                                    warn!(%err, "failed to reinit decoder on codec change");
                                }
                            }
                        }
                    }
                }

                let decode_start = Instant::now();
                let mut decoded_any = false;
                if let Some(dec) = decoder.as_mut() {
                    match dec.decode(data, assembled_frame.timestamp_ms as i64) {
                        Ok(nv12_frames) => {
                            if !nv12_frames.is_empty() {
                                decoded_any = true;
                                for nv12 in &nv12_frames {
                                    let size = (nv12.width, nv12.height);
                                    if last_logged_size != Some(size) {
                                        println!("decoded frame size {}x{}", size.0, size.1);
                                        last_logged_size = Some(size);
                                    }
                                }

                                if !has_options_requested || stream_options_active {
                                    decoded_frames =
                                        decoded_frames.saturating_add(nv12_frames.len() as u64);
                                }
                                first_frame_seen.store(true, Ordering::Relaxed);

                                if has_options_requested && !stream_options_sent {
                                    let host_supports_options = session
                                        .stream_state()
                                        .map(|s| s.host_supports_stream_options)
                                        .unwrap_or(false);
                                    if !host_supports_options {
                                        eprintln!("host does not support stream options");
                                        std::process::exit(1);
                                    }
                                    let scale_val = cli.scale.unwrap_or(1.0);
                                    let scale_permille =
                                        (scale_val * 1000.0).round().clamp(100.0, 1000.0) as u16;
                                    let req = StreamOptionsRequest {
                                        request_id: 1,
                                        scale_permille,
                                        fps: cli.fps.unwrap_or(60),
                                        codec: cli.codec.unwrap_or(StreamCodecPreference::Auto),
                                        display_index: cli.display.unwrap_or(0),
                                        bitrate: 0,
                                    };
                                    if let Err(e) = session.request_stream_options(req) {
                                        warn!(%e, "failed to send stream options request");
                                    } else {
                                        stream_options_sent = true;
                                    }
                                }

                                if let Some(last) = nv12_frames.last() {
                                    store_latest_frame(
                                        &latest_frame,
                                        &frame_metadata,
                                        &frame_snapshot,
                                        last,
                                        assembled_frame.header.frame_id as u64,
                                        cli.agent_server.is_some() || cli.mcp,
                                    );
                                }
                            }
                        }
                        Err(err) => {
                            decode_failed = true;
                            debug!(%err, is_key, size = data.len(), "Frame decode error");
                        }
                    }
                }

                if decode_failed {
                    decoder = None;
                    match frame_rx.decode_failed() {
                        Ok(true) => {
                            if let Err(error) =
                                session.send_control(ControlMessage::RequestKeyFrame)
                            {
                                warn!(%error, "decode recovery keyframe request failed");
                            }
                        }
                        Ok(false) => {}
                        Err(error) => {
                            error!(%error, "decode recovery queue failed");
                            break;
                        }
                    }
                }

                let decode_end = Instant::now();
                if decoded_any {
                    // Legacy interval: post-assembly queue entry through decode
                    // and optional agent-frame storage, not display presentation.
                    latency_recorder.record_sample(Some(receive_ts), decode_start, decode_end);
                    if decoded_frames <= 10
                        || decoded_frames % 20 == 0
                        || decoded_frames >= target_frames
                    {
                        info!(decoded_frames, target_frames, "Decoded frame progress");
                    }
                }
            }
            Err(mpsc::RecvTimeoutError::Timeout) => {
                continue;
            }
            Err(mpsc::RecvTimeoutError::Disconnected) => {
                media_closed = true;
            }
        }
    }

    running.store(false, Ordering::SeqCst);
    // Whatever ended the loop (SessionEnded, a dead runtime, the deadline),
    // a still-pending send gets one explicit outcome instead of vanishing.
    resolve_clipboard_send(
        &session,
        &mut pending_clipboard_send,
        ready_at.elapsed(),
        true,
    )?;
    #[cfg(target_os = "macos")]
    drop(clipboard_monitor);
    if let Some(stop) = mcp_stop.take() {
        // A closed receiver means the worker has already completed.
        stop.send_replace(true);
    }
    if let Some(stop_tx) = agent_server_stop.take() {
        let _ = stop_tx.send(true);
    }
    let frame_result = frame_rx.stop();
    let reached_target = decoded_frames >= target_frames;

    info!(
        decoded_frames,
        target_frames, "Cleaning up session transport..."
    );
    // The UDP reader has a bounded read timeout. Join it before freezing the
    // snapshot so no in-flight authenticated observation is lost to disconnect.
    let udp_result = udp_receiver_handle.and_then(|handle| {
        handle
            .join()
            .map_err(|_| anyhow::anyhow!("UDP receiver panicked"))
            .and_then(|result| result)
    });
    let receiver_result = session.receiver_snapshot();
    if let Ok(stats) = session.session_stats() {
        println!("network: RTT latest={:?}ms smoothed={:?}ms receive={:?} bytes/s loss={:?} decoder={:?}", stats.rtt_latest_ms, stats.rtt_smoothed_ms, stats.receive_bytes_per_second, stats.packet_loss_ratio, stats.decoder_backend);
    }
    let mcp_result = match mcp_handle {
        Some(handle) => handle
            .join()
            .map_err(|_| anyhow::anyhow!("MCP worker panicked"))
            .and_then(|result| result.context("MCP worker failed")),
        None => Ok(()),
    };
    let agent_result = if let Some(handle) = agent_server_handle {
        handle
            .join()
            .map_err(|_| anyhow::anyhow!("agent server worker thread panicked"))
            .and_then(|result| result.context("agent server worker failed"))
    } else {
        Ok(())
    };
    let transport_result = teardown(&session, &mut tcp_runtime);
    // Export even when transport cleanup failed, but never substitute an empty
    // snapshot for a failed acquisition. All teardown precedes fallible file I/O.
    let stats_result = receiver_result
        .context("failed to snapshot receiver statistics")
        .and_then(|receiver| stats_json(&latency_recorder, &receiver))
        .and_then(|json| {
            info!(stats = %json, "Headless decode and receiver statistics summary");
            write_stats_file(cli.stats_json.as_deref(), &json)
        });
    // Finish every cleanup/export before propagating errors, retaining secondary
    // failures as context instead of losing them behind the first `?`.
    let mut cleanup_result = Ok(());
    for result in [
        agent_spawn_result,
        frame_result,
        transport_result,
        udp_result,
        agent_result,
        mcp_result,
        stats_result,
    ] {
        if let Err(error) = result {
            cleanup_result = match cleanup_result {
                Ok(()) => Err(error),
                Err(previous) => Err(previous.context(error)),
            };
        }
    }
    cleanup_result?;

    if !reached_target && cli.deadline_expired(start_time.elapsed()) {
        bail!("timeout expired before decoding requested frames (got {decoded_frames}/{target_frames})");
    }

    Ok(())
}

fn run_agent_server_runtime(
    server: impl std::future::Future<Output = std::io::Result<()>>,
) -> std::io::Result<()> {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()?;
    let result = runtime.block_on(server);
    // The server already bounded its blocking-work drain. Implicit Drop would
    // wait forever for a backend that outlived that deadline, hiding its error.
    runtime.shutdown_background();
    result
}

/// Join the owned agent-server worker: returns as soon as the worker itself
/// ends (a disconnect request closes the listener), and otherwise asks it to
/// stop once the CLI lifecycle signals shutdown, still joining it here.
async fn join_agent_server_worker(
    mut server_task: tokio::task::JoinHandle<std::io::Result<()>>,
    shutdown_tx: tokio::sync::watch::Sender<bool>,
    mut stop_rx: tokio::sync::watch::Receiver<bool>,
) -> std::io::Result<()> {
    let outcome = tokio::select! {
        res = &mut server_task => res,
        _ = stop_rx.changed() => {
            let _ = shutdown_tx.send(true);
            server_task.await
        }
    };
    outcome.map_err(|err| std::io::Error::other(err.to_string()))?
}

fn teardown(session: &ClientSession, tcp_runtime: &mut ferryx_rd_app::SessionRuntime) -> Result<()> {
    // Send Disconnect / BYE control message
    let _ = session.send_control(ControlMessage::Disconnect);
    let runtime_result = tcp_runtime.stop();
    let disconnect_result = session.disconnect();
    runtime_result?;
    disconnect_result?;
    Ok(())
}

fn stats_json(recorder: &LatencyRecorder, receiver: &ReceiverSnapshot) -> Result<String> {
    #[derive(serde::Serialize)]
    struct Stats<'a> {
        #[serde(flatten)]
        legacy: ferryx_rd_app::LatencyStats,
        receiver_snapshot: &'a ReceiverSnapshot,
    }
    serde_json::to_string(&Stats {
        legacy: recorder.stats(),
        receiver_snapshot: receiver,
    })
    .context("failed to serialize CLI statistics")
}

fn write_stats_file(path: Option<&std::path::Path>, json: &str) -> Result<()> {
    if let Some(stats_path) = path {
        if let Some(parent) = stats_path
            .parent()
            .filter(|path| !path.as_os_str().is_empty())
        {
            fs::create_dir_all(parent).with_context(|| {
                format!("failed to create stats directory {}", parent.display())
            })?;
        }
        fs::write(stats_path, json.as_bytes())
            .with_context(|| format!("failed to write stats JSON to {}", stats_path.display()))?;
        info!("Stats JSON written to {}", stats_path.display());
    }
    Ok(())
}

fn ctrlc_handler<F>(f: F) -> Result<()>
where
    F: Fn() + Send + Sync + 'static,
{
    #[cfg(unix)]
    {
        use std::sync::OnceLock;

        extern "C" {
            fn signal(signum: i32, handler: extern "C" fn(i32)) -> usize;
        }

        const SIGINT: i32 = 2;
        const SIG_ERR: usize = usize::MAX;

        extern "C" fn on_signal(_signum: i32) {
            // The callback only performs an atomic store on the shutdown flag.
            if let Some(callback) = SIGNAL_CALLBACK.get() {
                callback();
            }
        }

        static SIGNAL_CALLBACK: OnceLock<&'static (dyn Fn() + Send + Sync)> = OnceLock::new();
        let leaked: &'static (dyn Fn() + Send + Sync) = Box::leak(Box::new(f));
        if SIGNAL_CALLBACK.set(leaked).is_err() {
            bail!("ctrl-c handler already installed");
        }
        let previous = unsafe { signal(SIGINT, on_signal) };
        if previous == SIG_ERR {
            bail!("failed to install SIGINT handler");
        }
    }
    #[cfg(not(unix))]
    {
        // Best-effort without a signal facility: keep the default handler.
        let _ = f;
    }
    Ok(())
}

