/// Validates the bootstrap PIN up front so a malformed value is reported as a
/// clap usage error instead of the misleading PSK identity failure downstream.
fn parse_pin(pin: &str) -> Result<String, String> {
    if pin.len() == 8 && pin.bytes().all(|byte| byte.is_ascii_digit()) {
        Ok(pin.to_string())
    } else {
        Err("--pin must be exactly 8 digits".to_string())
    }
}

fn parse_fps(fps: &str) -> Result<u16, String> {
    let val: u16 = fps.parse().map_err(|e| format!("invalid fps: {e}"))?;
    if (1..=240).contains(&val) {
        Ok(val)
    } else {
        Err("--fps must be between 1 and 240".to_string())
    }
}

fn parse_codec(codec: &str) -> Result<StreamCodecPreference, String> {
    match codec.to_ascii_lowercase().as_str() {
        "auto" => Ok(StreamCodecPreference::Auto),
        "h264" => Ok(StreamCodecPreference::H264),
        "hevc" => Ok(StreamCodecPreference::Hevc),
        _ => Err("--codec must be auto, h264, or hevc".to_string()),
    }
}

fn parse_scale(scale: &str) -> Result<f32, String> {
    let val: f32 = scale.parse().map_err(|e| format!("invalid scale: {e}"))?;
    if (0.1..=1.0).contains(&val) {
        Ok(val)
    } else {
        Err("--scale must be between 0.1 and 1.0".to_string())
    }
}

/// How long to wait for a GuestPermissions/HostPolicy before treating the host
/// as a pre-policy build whose clipboard gate is "allowed".
const CLIPBOARD_POLICY_GRACE: Duration = Duration::from_secs(2);

/// True once the host has told us its clipboard gate, via GuestPermissions or
/// HostPolicy.
fn clipboard_policy_known(session: &ClientSession) -> Result<bool> {
    Ok(session.session_info()?.permissions.is_some() || session.stream_state()?.policy.is_some())
}

/// Resolves a pending `--clipboard-send` exactly once. It waits while the
/// session is live and the host policy is still unknown (within the grace
/// period for pre-policy hosts); once the gate is settled, or the session is
/// over, it takes the request and prints a single outcome line.
fn resolve_clipboard_send(
    session: &ClientSession,
    pending: &mut Option<String>,
    since_ready: Duration,
    session_over: bool,
) -> Result<()> {
    if pending.is_none() {
        return Ok(());
    }
    let policy_known = clipboard_policy_known(session)?;
    if !(policy_known || session_over || since_ready >= CLIPBOARD_POLICY_GRACE) {
        return Ok(());
    }
    let Some(text) = pending.take() else {
        return Ok(());
    };
    if session_over && !policy_known {
        println!(
            "clipboard send refused: session ended before the host clipboard policy was known"
        );
        return Ok(());
    }
    let bytes = text.len();
    match session.send_clipboard_text(text) {
        Ok(()) => println!("clipboard sent: {bytes} bytes"),
        Err(error) => println!("clipboard send refused: {error}"),
    }
    Ok(())
}

#[cfg(target_os = "macos")]
fn start_clipboard_watch(
    session: &ClientSession,
) -> Option<ferryx_rd_app::ClipboardMonitor<ferryx_rd_app::platform::SystemClipboard>> {
    let mut monitor = match ferryx_rd_app::ClipboardMonitor::new(ferryx_rd_app::platform::SystemClipboard) {
        Ok(monitor) => monitor,
        Err(error) => {
            println!("clipboard watch unavailable: {error}");
            return None;
        }
    };
    let session = session.clone();
    let started = monitor.start(move |text| {
        let bytes = text.len();
        match session.send_clipboard_text(text) {
            Ok(()) => println!("clipboard sent: {bytes} bytes"),
            Err(error) => println!("clipboard send refused: {error}"),
        }
    });
    match started {
        Ok(()) => {
            info!("watching local pasteboard for clipboard changes");
            Some(monitor)
        }
        Err(error) => {
            println!("clipboard watch unavailable: {error}");
            None
        }
    }
}

type LatestFrameHolder = Arc<std::sync::Mutex<Option<(u32, u32, Arc<Vec<u8>>)>>>;
type FrameMetadataHolder = Arc<std::sync::Mutex<Option<(FrameMetadata, Instant)>>>;
type FrameSnapshotHolder =
    Arc<std::sync::Mutex<Option<(u32, u32, Arc<Vec<u8>>, FrameMetadata, Instant)>>>;

impl Cli {
    fn deadline_expired(&self, elapsed: Duration) -> bool {
        self.timeout_secs
            .or_else(|| {
                (!(self.mcp || self.agent_server.is_some())).then_some(DEFAULT_TIMEOUT_SECS)
            })
            .is_some_and(|seconds| elapsed >= Duration::from_secs(seconds))
    }
}

#[derive(Clone)]
struct ClientBackend {
    session: ClientSession,
    /// Stored pairing used to re-handshake when the host swaps its worker.
    pairing_id: Option<String>,
    screen_info: ScreenInfo,
    latest_frame: LatestFrameHolder,
    frame_metadata: FrameMetadataHolder,
    frame_snapshot: FrameSnapshotHolder,
    running: Arc<AtomicBool>,
}

impl AgentServerBackend for ClientBackend {
    fn send_input_event(&self, event: ferryx_rd_proto::InputEvent) -> std::result::Result<(), String> {
        match self.session.send_input(event) {
            Ok(()) => Ok(()),
            Err(error) if ferryx_rd_app::should_reconnect(&error) => {
                // The host service replaces its session worker whenever the
                // console switches desktop, which tears down this client's
                // control channel. Re-handshake with the stored pairing and
                // retry once so a secure-desktop switch cannot strand us.
                let pairing_id = self
                    .pairing_id
                    .as_deref()
                    .ok_or_else(|| error.to_string())?;
                self.session
                    .reconnect(pairing_id)
                    .map_err(|retry| format!("{error}; reconnect failed: {retry}"))?;
                self.session
                    .send_input(event)
                    .map_err(|retry| retry.to_string())
            }
            Err(error) => Err(error.to_string()),
        }
    }

    fn get_screen_info(&self) -> ScreenInfo {
        self.screen_info.clone()
    }

    fn get_latest_frame_nv12(&self) -> Option<(u32, u32, Arc<Vec<u8>>)> {
        self.latest_frame.lock().ok()?.clone()
    }

    fn get_latest_frame_metadata(&self) -> Option<FrameMetadata> {
        let lock = self.frame_metadata.lock().ok()?;
        let (mut meta, received_at) = (*lock)?;
        meta.age_ms = received_at.elapsed().as_millis() as u64;
        Some(meta)
    }

    fn get_latest_frame_snapshot(&self) -> Option<ferryx_rd_app::agent_server::FrameSnapshot> {
        let lock = self.frame_snapshot.lock().ok()?;
        let (width, height, buffer, mut meta, received_at) = lock.as_ref()?.clone();
        meta.age_ms = received_at.elapsed().as_millis() as u64;
        Some(ferryx_rd_app::agent_server::FrameSnapshot {
            width,
            height,
            buffer,
            metadata: Some(meta),
        })
    }

    fn supports_session_disconnect(&self) -> bool {
        true
    }

    fn try_disconnect_session(&self) -> std::result::Result<(), String> {
        // Flip the CLI's own lifecycle flag: the existing main loop then runs
        // its normal cleanup (frame queue stop, Disconnect/BYE, TCP stop,
        // session disconnect) exactly as on a timeout shutdown.
        self.running.store(false, Ordering::SeqCst);
        Ok(())
    }
}

fn store_latest_frame(
    latest_frame: &LatestFrameHolder,
    frame_metadata: &FrameMetadataHolder,
    frame_snapshot: &FrameSnapshotHolder,
    last: &ferryx_rd_decode::Nv12Frame,
    frame_id: u64,
    enabled: bool,
) {
    if !enabled {
        return;
    }
    let w = last.width as usize;
    let h = last.height as usize;
    let y_len = w * h;
    let uv_len = w * h.div_ceil(2);
    let mut buf = Vec::with_capacity(y_len + uv_len);
    if last.y_plane.len() >= y_len {
        buf.extend_from_slice(&last.y_plane[..y_len]);
    } else {
        buf.extend_from_slice(&last.y_plane);
        buf.resize(y_len, 0);
    }
    if last.uv_plane.len() >= uv_len {
        buf.extend_from_slice(&last.uv_plane[..uv_len]);
    } else {
        buf.extend_from_slice(&last.uv_plane);
        buf.resize(y_len + uv_len, 128);
    }
    let buf_arc = Arc::new(buf);
    let now = Instant::now();
    let meta = FrameMetadata {
        frame_id,
        timestamp_ms: last.timestamp_ms as u64,
        age_ms: 0,
    };
    if let Ok(mut lock) = frame_snapshot.lock() {
        *lock = Some((last.width, last.height, buf_arc.clone(), meta, now));
    }
    if let Ok(mut lock) = latest_frame.lock() {
        *lock = Some((last.width, last.height, buf_arc));
    }
    // Update frame metadata
    if let Ok(mut lock) = frame_metadata.lock() {
        *lock = Some((meta, now));
    }
}

