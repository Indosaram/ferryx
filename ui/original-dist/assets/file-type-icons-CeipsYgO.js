var COMPOUND_EXTENSIONS = [
	"tar.bz2",
	"tar.gz",
	"tar.xz"
];
function getFilename(filePath) {
	if (!filePath) return "";
	const lastSlash = Math.max(filePath.lastIndexOf("/"), filePath.lastIndexOf("\\"));
	return lastSlash >= 0 ? filePath.slice(lastSlash + 1) : filePath;
}
function getExtension(filename) {
	const lowerName = filename.toLowerCase();
	const compoundExtension = COMPOUND_EXTENSIONS.find((ext) => lowerName.endsWith(`.${ext}`));
	if (compoundExtension) return compoundExtension;
	const lastDot = filename.lastIndexOf(".");
	if (lastDot <= 0 || lastDot === filename.length - 1) return "";
	return filename.slice(lastDot + 1).toLowerCase();
}
function getFileTypeIcon(filePath) {
	const filename = getFilename(filePath);
	if (!filename) return File;
	const lowerName = filename.toLowerCase();
	const exactMatch = FILE_ICON_BY_NAME[lowerName];
	if (exactMatch) return exactMatch;
	if (lowerName === "mobile emulator" || lowerName === "simulator") return Smartphone;
	if (lowerName === ".env" || lowerName.startsWith(".env.")) return FileLock;
	if (lowerName === "dockerfile" || lowerName.startsWith("dockerfile.")) return FileCog;
	if (lowerName === "makefile" || lowerName.startsWith("makefile.")) return FileTerminal;
	return FILE_ICON_BY_EXTENSION[getExtension(filename)] ?? File;
}
