function normalizeRichMarkdownDocument(editor, options) {
	const { doc, schema } = editor.view.state;
	const paragraphType = schema.nodes.paragraph;
	if (!paragraphType) return;
	const replacements = [];
	doc.descendants((node, pos) => {
		if (node.type.name === "listItem" && node.childCount === 0) {
			replacements.push({
				from: pos,
				to: pos + node.nodeSize,
				kind: "empty-list-item",
				node: node.type.create(node.attrs, paragraphType.create(), node.marks)
			});
			return false;
		}
		if (node.type !== paragraphType) return true;
		if (!options.splitSoftBreakParagraphs) return false;
		if (!node.textContent.includes("\n")) return false;
		const lines = [];
		let currentNodes = [];
		node.content.forEach((child) => {
			if (!child.isText || !child.text?.includes("\n")) {
				currentNodes.push(child);
				return;
			}
			const text = child.text;
			let segmentStart = 0;
			for (let index = 0; index <= text.length; index += 1) {
				if (index < text.length && text.charCodeAt(index) !== 10) continue;
				if (index > segmentStart) currentNodes.push(schema.text(text.slice(segmentStart, index), child.marks));
				if (index < text.length) {
					lines.push(Fragment.from(currentNodes));
					currentNodes = [];
					segmentStart = index + 1;
				}
			}
		});
		lines.push(Fragment.from(currentNodes));
		if (lines.length <= 1) return false;
		replacements.push({
			from: pos,
			to: pos + node.nodeSize,
			kind: "soft-break-paragraphs",
			paragraphs: lines
		});
		return false;
	});
	if (replacements.length === 0) return;
	const tr = editor.view.state.tr;
	replacements.sort((a, b) => b.from - a.from);
	for (const replacement of replacements) {
		if (replacement.kind === "empty-list-item") {
			tr.replaceWith(replacement.from, replacement.to, replacement.node);
			continue;
		}
		const newNodes = replacement.paragraphs.map((content) => paragraphType.create(null, content));
		tr.replaceWith(replacement.from, replacement.to, newNodes);
	}
	editor.view.dispatch(tr.setMeta("addToHistory", false));
}
