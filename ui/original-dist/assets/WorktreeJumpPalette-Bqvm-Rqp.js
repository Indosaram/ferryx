function cmdJPaletteTokenScore(query, values) {
	const candidateTokens = values.flatMap(tokenizeCmdJPaletteQuery);
	if (candidateTokens.length === 0) return 0;
	let score = 0;
	let meaningful = 0;
	let covered = 0;
	for (const queryToken of tokenizeCmdJPaletteQuery(query)) {
		let best = 0;
		for (const candidateToken of candidateTokens) if (candidateToken === queryToken) best = Math.max(best, 3);
		else if (candidateToken.startsWith(queryToken)) best = Math.max(best, 2);
		else if (candidateToken.includes(queryToken)) best = Math.max(best, 1);
		score += best;
		if (CMD_J_QUERY_FILLER_TOKENS.has(queryToken)) continue;
		meaningful += 1;
		if (best > 0) covered += 1;
	}
	if (meaningful > 0 && covered * 2 <= meaningful) return 0;
	return score;
}
