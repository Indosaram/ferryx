function rankingForCandidate(query, candidate, actionVerbKeywords, settingsConfigKeywords) {
	if (!query) return null;
	const score = cmdJPaletteTokenScore(query, candidate.kind === "settings" ? [candidate.title, ...candidate.configKeywords] : [candidate.title, ...candidate.verbKeywords]);
	if (score === 0) return null;
	if (candidate.kind === "action" && candidate.verbKeywords.some((keyword) => query === keyword)) return {
		result: candidate,
		rule: 1,
		score: 0
	};
	if (candidate.kind === "settings" && candidate.configKeywords.some((keyword) => query === keyword)) return {
		result: candidate,
		rule: 2,
		score: 0
	};
	if (candidate.kind === "settings" && actionVerbKeywords.some((keyword) => query.startsWith(keyword)) && candidate.configKeywords.some((keyword) => query.endsWith(keyword))) return {
		result: candidate,
		rule: 3,
		score: 0
	};
	if (candidate.kind === "action" && candidate.verbKeywords.some((keyword) => startsOrIsStartedBy(query, keyword)) && !settingsConfigKeywords.some((keyword) => query.endsWith(keyword))) return {
		result: candidate,
		rule: 4,
		score: 0
	};
	if (candidate.kind === "settings" && candidate.configKeywords.some((keyword) => keyword.startsWith(query) && keyword !== query)) return {
		result: candidate,
		rule: 5,
		score: 0
	};
	return {
		result: candidate,
		rule: 6,
		score
	};
}
function compareRanked(a, b) {
	if (a.rule !== b.rule) return a.rule - b.rule;
	if (a.rule === 6 && a.score !== b.score) return b.score - a.score;
	if (a.result.kind !== b.result.kind) return a.result.kind === "settings" ? -1 : 1;
	if (a.result.order !== b.result.order) return a.result.order - b.result.order;
	return a.result.id.localeCompare(b.result.id);
}
