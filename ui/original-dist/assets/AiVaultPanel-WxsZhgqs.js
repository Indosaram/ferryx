function formatTimeAgo(timestamp) {
	const diffMs = Date.now() - timestamp;
	if (diffMs < 6e4) return translate("auto.components.right.sidebar.AiVaultSessionDetails.justNow", "Just now");
	const minutes = Math.floor(diffMs / 6e4);
	if (minutes < 60) return translate("auto.components.right.sidebar.AiVaultSessionDetails.minutesAgo", "{{value0}}m ago", { value0: minutes });
	const hours = Math.floor(minutes / 60);
	if (hours < 24) return translate("auto.components.right.sidebar.AiVaultSessionDetails.hoursAgo", "{{value0}}h ago", { value0: hours });
	const days = Math.floor(hours / 24);
	if (days < 30) return translate("auto.components.right.sidebar.AiVaultSessionDetails.daysAgo", "{{value0}}d ago", { value0: days });
	const months = Math.floor(days / 30);
	if (months < 12) return translate("auto.components.right.sidebar.AiVaultSessionDetails.monthsAgo", "{{value0}}mo ago", { value0: months });
	return translate("auto.components.right.sidebar.AiVaultSessionDetails.yearsAgo", "{{value0}}y ago", { value0: Math.floor(months / 12) });
}
