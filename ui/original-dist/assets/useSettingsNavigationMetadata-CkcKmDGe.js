function useSettingsNavigationMetadata() {
	const { i18n } = useTranslation();
	const activeLocale = i18n.language;
	const repos = useAppStore((state) => state.repos);
	const settings = useAppStore((state) => state.settings);
	const [managedBrowserCreationEnabled, mobileEmulatorCreationEnabled] = useAppStore(useShallow((state) => {
		const policy = getClientCreationActionPolicy(state, state.activeWorktreeId);
		return [policy["managed-browser"].state === "enabled", policy["mobile-emulator"].state === "enabled"];
	}));
	const isMac = isMacUserAgent();
	const isWindows = isWindowsUserAgent();
	const isWebClient = isWebClientLocation();
	const isLinearConnected = useLinearProviderConnected();
	const windowsTerminalCapabilityOwnerKey = useWindowsTerminalCapabilityOwnerKey(settings?.activeRuntimeEnvironmentId);
	const runtimeTarget = getActiveRuntimeTarget(settings);
	const capabilityLoadTarget = isWebClient ? { kind: "local" } : runtimeTarget;
	const windowsTerminalCapabilities = useWindowsTerminalCapabilities(isWindows || isWebClient || runtimeTarget.kind === "environment", false, windowsTerminalCapabilityOwnerKey, capabilityLoadTarget);
	const isLocalWindowsHost = isWindowsTerminalCapabilityHost({
		isWindowsRenderer: isWindows,
		isWebClient,
		target: { kind: "local" },
		hostPlatform: isWebClient || runtimeTarget.kind === "local" ? windowsTerminalCapabilities.hostPlatform : null
	});
	const isWindowsTerminalHost = isWindowsTerminalCapabilityHost({
		isWindowsRenderer: isWindows,
		isWebClient,
		target: runtimeTarget,
		hostPlatform: windowsTerminalCapabilities.hostPlatform
	});
	return (0, import_react.useMemo)(() => buildSettingsNavigationMetadata({
		isMac,
		isWindows,
		isLocalWindowsHost,
		isWindowsTerminalHost,
		isWebClient,
		managedBrowserCreationEnabled,
		mobileEmulatorCreationEnabled,
		isDev: false,
		isLinearConnected,
		repos
	}), [
		isMac,
		isWindows,
		isLocalWindowsHost,
		isWindowsTerminalHost,
		isWebClient,
		managedBrowserCreationEnabled,
		mobileEmulatorCreationEnabled,
		isLinearConnected,
		repos,
		activeLocale
	]);
}
