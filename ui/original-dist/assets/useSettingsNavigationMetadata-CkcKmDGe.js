function resolveSettingsTargetRepoId(target, repoIds) {
	if (target.repoId) return target.repoId;
	const sectionId = target.sectionId;
	if (!sectionId || !sectionId.startsWith("repo-")) return null;
	let best = null;
	for (const repoId of repoIds) if (sectionId === `repo-${repoId}` || sectionId.startsWith(`repo-${repoId}-`)) {
		if (best === null || repoId.length > best.length) best = repoId;
	}
	return best;
}
