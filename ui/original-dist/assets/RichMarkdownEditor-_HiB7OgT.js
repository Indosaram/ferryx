function normalizeSelectedText(value) {
	let normalized = "";
	let previousWasWhitespace = false;
	for (let index = 0; index < value.length; index += 1) {
		if (isRichMarkdownWhitespace(value.charCodeAt(index))) {
			if (normalized.length > 0 && !previousWasWhitespace) normalized += " ";
			previousWasWhitespace = true;
			continue;
		}
		normalized += value.charAt(index);
		previousWasWhitespace = false;
	}
	return normalized;
}
function processRawTextChar(char, normalizationState, matchState) {
	if (isRichMarkdownWhitespace(char.value.charCodeAt(0))) {
		if (!normalizationState.previousWasWhitespace) processNormalizedTextChar({
			value: " ",
			pos: char.pos
		}, matchState);
		normalizationState.previousWasWhitespace = true;
		return;
	}
	processNormalizedTextChar(char, matchState);
	normalizationState.previousWasWhitespace = false;
}
function processNormalizedTextChar(char, matchState) {
	recordRecentPosition(char.pos, matchState);
	while (matchState.matchLength > 0 && char.value !== matchState.needle[matchState.matchLength]) matchState.matchLength = matchState.prefixTable[matchState.matchLength - 1] ?? 0;
	if (char.value !== matchState.needle[matchState.matchLength]) return;
	matchState.matchLength += 1;
	if (matchState.matchLength === matchState.needle.length) matchState.positions = readRecentPositions(matchState);
}
function recordRecentPosition(pos, matchState) {
	if (matchState.recentPositions.length < matchState.needle.length) {
		matchState.recentPositions.push(pos);
		matchState.recentPositionWriteIndex = matchState.recentPositions.length % matchState.needle.length;
		return;
	}
	matchState.recentPositions[matchState.recentPositionWriteIndex] = pos;
	matchState.recentPositionWriteIndex = (matchState.recentPositionWriteIndex + 1) % matchState.needle.length;
}
function readRecentPositions(matchState) {
	const positions = [];
	for (let index = 0; index < matchState.needle.length; index += 1) {
		const bufferIndex = (matchState.recentPositionWriteIndex + index) % matchState.needle.length;
		positions.push(matchState.recentPositions[bufferIndex] ?? null);
	}
	return positions;
}
function buildPrefixTable(value) {
	const table = [];
	for (let index = 0; index < value.length; index += 1) table.push(0);
	let prefixLength = 0;
	for (let index = 1; index < value.length; index += 1) {
		while (prefixLength > 0 && value[index] !== value[prefixLength]) prefixLength = table[prefixLength - 1] ?? 0;
		if (value[index] === value[prefixLength]) {
			prefixLength += 1;
			table[index] = prefixLength;
		}
	}
	return table;
}
function positionsToRanges(positions) {
	const ranges = [];
	let rangeFrom = null;
	let rangeTo = null;
	for (const position of positions) {
		if (position === null) continue;
		if (rangeFrom === null || rangeTo === null) {
			rangeFrom = position.from;
			rangeTo = position.to;
			continue;
		}
		if (position.from <= rangeTo) {
			rangeTo = Math.max(rangeTo, position.to);
			continue;
		}
		ranges.push({
			from: rangeFrom,
			to: rangeTo
		});
		rangeFrom = position.from;
		rangeTo = position.to;
	}
	if (rangeFrom !== null && rangeTo !== null) ranges.push({
		from: rangeFrom,
		to: rangeTo
	});
	return ranges;
}
