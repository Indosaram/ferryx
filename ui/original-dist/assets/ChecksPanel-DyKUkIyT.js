function installWindowVisibilityTimeoutPoller(args) {
	const setTimeoutFn = args.setTimeoutFn ?? ((callback, delayMs) => setTimeout(callback, delayMs));
	const clearTimeoutFn = args.clearTimeoutFn ?? ((handle) => clearTimeout(handle));
	let timeoutId = null;
	let disposed = false;
	let inFlight = false;
	const clearScheduledPoll = () => {
		if (!timeoutId) return;
		clearTimeoutFn(timeoutId);
		timeoutId = null;
	};
	const schedulePoll = () => {
		clearScheduledPoll();
		if (disposed || !isWindowVisible()) return;
		timeoutId = setTimeoutFn(() => {
			timeoutId = null;
			runAndSchedule();
		}, args.getDelayMs());
	};
	function runAndSchedule() {
		clearScheduledPoll();
		if (disposed || !isWindowVisible() || inFlight) return;
		inFlight = true;
		Promise.resolve(args.run()).finally(() => {
			inFlight = false;
			schedulePoll();
		});
	}
	const reconcileVisibility = () => {
		if (isWindowVisible()) runAndSchedule();
		else clearScheduledPoll();
	};
	runAndSchedule();
	if (typeof window !== "undefined" && typeof window.addEventListener === "function") window.addEventListener("focus", reconcileVisibility);
	if (typeof document !== "undefined" && typeof document.addEventListener === "function") document.addEventListener("visibilitychange", reconcileVisibility);
	return () => {
		disposed = true;
		clearScheduledPoll();
		if (typeof window !== "undefined" && typeof window.removeEventListener === "function") window.removeEventListener("focus", reconcileVisibility);
		if (typeof document !== "undefined" && typeof document.removeEventListener === "function") document.removeEventListener("visibilitychange", reconcileVisibility);
	};
}
