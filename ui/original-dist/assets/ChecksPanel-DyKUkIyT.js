function buildSnapshottedThreadResolver(deps) {
	return async (threadId) => {
		const outcome = await resolveOnHost(deps, threadId);
		if (!outcome.ok) {
			deps.onResolveFailed({
				threadId,
				error: outcome.error
			});
			return false;
		}
		if (deps.isPanelStillOnLaunchReview()) deps.onResolvedOptimistically(threadId);
		return true;
	};
}
async function resolveOnHost(deps, threadId) {
	try {
		if (deps.provider === "gitlab") {
			if (!deps.gitlabTarget) return { ok: false };
			return await deps.resolveGitLabDiscussion({
				repoPath: deps.gitlabTarget.repoPath,
				repoId: deps.gitlabTarget.repoId,
				iid: deps.gitlabTarget.iid,
				discussionId: threadId,
				resolved: true
			});
		}
		if (deps.provider !== "github" || !deps.githubResolveTarget) return { ok: false };
		const target = deps.githubResolveTarget;
		return { ok: await deps.resolveReviewThread(target.repoPath, target.prNumber, threadId, true, {
			repoId: target.repoId,
			prRepo: target.prRepo
		}) };
	} catch (err) {
		return {
			ok: false,
			error: err instanceof Error ? err.message : String(err)
		};
	}
}
