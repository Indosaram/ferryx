#!/usr/bin/env bun
/**
 * Writes the CSS custom property blocks of ui/src/index.css and ui/src/settings-runtime.css
 * from ui/src/tokens. Each generated region sits between
 *   /* @tokens <id>: ... *\/   and   /* @tokens-end <id> *\/
 * inside its selector block; selectors and everything outside the regions are hand-written.
 *
 *   bun ui/scripts/gen-token-css.ts           rewrite the regions
 *   bun ui/scripts/gen-token-css.ts --check   exit 1 when a region is stale (run by `lint`)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { colors, density, radius, type ColorTokenBlock } from "../src/tokens";

const uiRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const HEX = /^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;

type Declarations = Readonly<Record<string, string>>;

function rgbTwin(hex: string): string {
  return [1, 3, 5].map((offset) => parseInt(hex.slice(offset, offset + 2), 16)).join(" ");
}

/** Color tokens become custom properties; each hex color gets its `-rgb` twin for Tailwind. */
function colorDeclarations(...blocks: ColorTokenBlock[]): string[] {
  const lines: string[] = [];
  for (const block of blocks) {
    for (const [name, value] of Object.entries(block)) {
      lines.push(`--${name}: ${value};`);
      if (!name.endsWith("-alpha") && HEX.test(value)) lines.push(`--${name}-rgb: ${rgbTwin(value)};`);
    }
  }
  return lines;
}

function plainDeclarations(block: Declarations): string[] {
  return Object.entries(block).map(([name, value]) => `${name}: ${value};`);
}

const accentRegions = Object.fromEntries(
  Object.entries(colors.accents).map(([name, block]) => [
    `accent-${name}`,
    colorDeclarations(block),
  ]),
);

export const TOKEN_CSS_FILES: Record<string, Record<string, string[]>> = {
  "src/index.css": {
    root: [`--radius: ${radius};`, ...colorDeclarations(colors.base, colors.semantic)],
    "root-light": colorDeclarations(colors.baseLight),
    // Redeclared on the remote root so the var() references resolve against its own palette.
    remote: colorDeclarations(colors.remote, colors.semantic),
    "remote-light": colorDeclarations(colors.remoteLight, colors.semantic),
  },
  "src/settings-runtime.css": {
    "theme-dark": colorDeclarations(colors.themeDark),
    "theme-light": colorDeclarations(colors.themeLight, colors.semanticLight),
    ...accentRegions,
    "density-compact": plainDeclarations(density.compact),
    "density-comfortable": plainDeclarations(density.comfortable),
  },
};

const REGION = /^([ \t]*)\/\* @tokens ([\w-]+):[^*]*\*\/\n[\s\S]*?^[ \t]*\/\* @tokens-end \2 \*\/$/gm;

/** Returns the file with every region regenerated; throws on a missing or unknown region. */
export function renderTokenCss(file: string, source: string): string {
  const regions = TOKEN_CSS_FILES[file];
  const seen = new Set<string>();
  const output = source.replace(REGION, (_match, indent: string, id: string) => {
    const lines = regions[id];
    if (!lines) throw new Error(`${file}: unknown token region "${id}"`);
    seen.add(id);
    return [
      `${indent}/* @tokens ${id}: generated by ui/scripts/gen-token-css.ts from ui/src/tokens, do not edit */`,
      ...lines.map((line) => `${indent}${line}`),
      `${indent}/* @tokens-end ${id} */`,
    ].join("\n");
  });
  const missing = Object.keys(regions).filter((id) => !seen.has(id));
  if (missing.length > 0) throw new Error(`${file}: missing token region(s) ${missing.join(", ")}`);
  return output;
}

function main(argv: string[]): number {
  const check = argv.includes("--check");
  const stale: string[] = [];
  for (const file of Object.keys(TOKEN_CSS_FILES)) {
    const path = join(uiRoot, file);
    const source = readFileSync(path, "utf8");
    const next = renderTokenCss(file, source);
    if (next === source) continue;
    if (check) stale.push(relative(process.cwd(), path));
    else writeFileSync(path, next);
  }
  if (stale.length > 0) {
    console.error(`gen-token-css: stale token CSS in ${stale.join(", ")}; run bun ui/scripts/gen-token-css.ts`);
    return 1;
  }
  console.log(check ? "gen-token-css: token CSS is current" : "gen-token-css: token CSS written");
  return 0;
}

const entry = process.argv[1];
if (entry && resolve(entry) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
